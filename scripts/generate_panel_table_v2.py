"""Emit every number the manuscript's dataset description prints, from the panel.

Run:  PYTHONPATH=scripts uv run --no-project --with numpy --python 3.12 \
          python scripts/generate_panel_description.py

D3 and D9 in docs/OPEN_DEFECTS.md are the same defect twice: panel statistics and
a class breakdown carried by hand from the 12-family pilot into a manuscript
describing the expanded panel, and left there through the Rfam expansion, the
duplicate-annotation correction and the annotation repair. Correcting the numbers
by hand would reproduce the defect at the next correction, so this script writes
them and paper/generated/panel_description.tex is what the manuscript includes.

The panel is the set of records `load_rfam_families` loads: 52 curated, minus the
records withdrawn by repair_annotations.py, which carry an `excluded` block.

No model is run.
"""

import json
from pathlib import Path

from audit_panel_classes import classify

REPO = Path(__file__).resolve().parents[1]
FAMILIES = REPO / "data/rfam_families"
TABLE = REPO / "paper/generated_v24/panel_table_v2.tex"
MANIFEST = REPO / "docs/annotation_repair_manifest.json"

# repair_annotations.py's disposition, as the supplement reports it.
DISPOSITION = {"ADOPT STRUCTURE": "structure repaired", "ADOPT MEMBER": "record repaired",
               "DROP": "withdrawn", "DEFER": "withdrawn", "NO REPAIR": ""}


def panel() -> tuple[list[dict], list[dict]]:
    """(analyzed, withdrawn) -- every curated record, split by the exclusion block."""
    records = [json.loads(p.read_text()) for p in sorted(FAMILIES.glob("*.json"))]
    return ([r for r in records if "excluded" not in r],
            [r for r in records if "excluded" in r])


def gc(record: dict) -> tuple[float, float] | None:
    """(stem GC%, loop GC%), or None when the annotation has no stem or no loop."""
    sequence, brackets = record["sequence"].upper(), record["dot_bracket"]
    stem = [i for i, c in enumerate(brackets) if c in "()"]
    loop = [i for i, c in enumerate(brackets) if c == "."]
    if not stem or not loop:
        return None
    return (sum(sequence[i] in "GC" for i in stem) / len(stem) * 100,
            sum(sequence[i] in "GC" for i in loop) / len(loop) * 100)


def accession(record: dict) -> str:
    """The seed member a record names, or an em dash when it names none."""
    source = record.get("source") or ""
    marker = "seed alignment member ("
    return source[source.index(marker) + len(marker):-1] if marker in source else "---"


def tex(text: str) -> str:
    """Escape the characters a family name, accession or reason can carry."""
    for char in ("\\", "_", "%", "&", "#", "$"):
        text = text.replace(char, "\\" + char)
    return text


def panel_table(analyzed: list[dict], withdrawn: list[dict]) -> str:
    disposition = {d["name"]: DISPOSITION[d["disposition"]]
                   for d in json.loads(MANIFEST.read_text())["decisions"]}
    rows = []
    for record in sorted(analyzed, key=lambda r: r["name"]) + \
            sorted(withdrawn, key=lambda r: r["name"]):
        note = disposition.get(record["name"], "")
        if "excluded" in record:
            note = f"withdrawn: {record['excluded']['reason']}"
        rows.append(" & ".join([
            tex(record["name"]),
            classify(record["name"]),
            record.get("rfam_id") or "---",
            tex(accession(record)),
            str(record["length"]),
            tex(note)]) + r" \\")
    return "\n".join([
        r"% Generated by scripts/generate_panel_description.py. Do not edit.",
        # Every column gets an explicit share of \textwidth. With five natural-width
        # columns and only Note wrapped, the table sized itself 164pt past the text
        # block and the withdrawal reasons were cut off mid-word in the PDF.
        r"\begingroup\footnotesize\setlength{\tabcolsep}{4pt}",
        r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.195\textwidth}>{\raggedright\arraybackslash}p{0.14\textwidth}>{\raggedright\arraybackslash}p{0.07\textwidth}>{\raggedright\arraybackslash}p{0.245\textwidth}>{\raggedleft\arraybackslash}p{0.035\textwidth}>{\raggedright\arraybackslash}p{0.215\textwidth}@{}}",
        r"\caption{The curated panel. Families above the rule are analyzed; those "
        r"below carry an annotation that could not be repaired against the Rfam "
        r"seed alignment and are withdrawn. Accession names the seed member a "
        r"record's sequence and structure come from.}"
        r"\label{tab:panel}\\",
        r"\toprule",
        r"\textbf{Family} & \textbf{Class} & \textbf{Rfam} & "
        r"\textbf{Accession} & \textbf{nt} & \textbf{Note} \\",
        r"\midrule\endfirsthead",
        r"\toprule",
        r"\textbf{Family} & \textbf{Class} & \textbf{Rfam} & "
        r"\textbf{Accession} & \textbf{nt} & \textbf{Note} \\",
        r"\midrule\endhead",
        *rows[:len(analyzed)],
        r"\midrule",
        *rows[len(analyzed):],
        r"\bottomrule",
        r"\end{longtable}",
        r"\endgroup"])


def main() -> None:
    """The panel table only, with the accession column wide enough for its entries.

    `generate_panel_description.py` set that column at 0.215 of the text width,
    and six accessions ran past it by up to 10.6pt. The macros that script
    writes are not rewritten here.
    """
    analyzed, withdrawn = panel()
    TABLE.write_text(panel_table(analyzed, withdrawn).replace(
        "generate_panel_description.py", "generate_panel_table_v2.py") + "\n")
    print(f"  -> {TABLE.relative_to(REPO)}")


if __name__ == "__main__":
    main()
